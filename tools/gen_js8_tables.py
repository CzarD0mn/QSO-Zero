#!/usr/bin/env python3
"""Regenerate src/dsp/js8_tables.h from a JS8Call checkout:
    python3 tools/gen_js8_tables.py /path/to/js8call/JS8.cpp > src/dsp/js8_tables.h
Extracts the LDPC(174,87) Mn/Nm tables and the generator matrix, and refuses
to write anything unless every generator codeword satisfies every check."""
import re, sys, random
src = open(sys.argv[1]).read()
mn = [tuple(map(int, t)) for t in re.findall(r'\{\s*(\d+),\s*(\d+),\s*(\d+)\}', re.search(r'Mn =\s*\{\{(.*?)\}\};', src, re.S).group(1))]
nm = [(int(a), list(map(int, b.split(',')))) for a, b in re.findall(r'\{(\d),\s*\{([\d,\s]+)\}\}', re.search(r'Nm =\s*\{\{(.*?)\}\};', src, re.S).group(1))]
par = re.findall(r'"([0-9a-f]{22})"', re.search(r'Data =\s*\{(.*?)\};', src, re.S).group(1))
assert len(mn) == 174 and len(nm) == 87 and len(par) == 87
assert {(c, v) for v, cs in enumerate(mn) for c in cs} == {(c, v) for c, (n, vs) in enumerate(nm) for v in vs[:n]}
P = [[(int(h, 16) >> (87 - j)) & 1 for j in range(87)] for h in par]
for _ in range(50):
    m = [random.randint(0, 1) for _ in range(87)]
    cw = [sum(P[i][j] & m[j] for j in range(87)) & 1 for i in range(87)] + m
    assert all(sum(cw[v] for v in vs[:n]) % 2 == 0 for n, vs in nm)
o = sys.stdout
o.write("/* LDPC(174,87) tables for JS8, extracted verbatim from JS8Call JS8.cpp (GPLv3).\n * Generated by tools/gen_js8_tables.py; verified H*G^T = 0. */\n")
o.write("static const int16_t js8_Mn[174][3] = {\n")
for i in range(0, 174, 6): o.write("  " + ", ".join("{%d,%d,%d}" % t for t in mn[i:i+6]) + ",\n")
o.write("};\nstatic const uint8_t js8_Nm_count[87] = {" + ",".join(str(n) for n, _ in nm) + "};\n")
o.write("static const int16_t js8_Nm[87][7] = {\n")
for i in range(0, 87, 4): o.write("  " + ", ".join("{" + ",".join(map(str, vs)) + "}" for _, vs in nm[i:i+4]) + ",\n")
o.write("};\nstatic const char *const js8_parity_hex[87] = {\n")
for i in range(0, 87, 3): o.write("  " + ", ".join('"%s"' % h for h in par[i:i+3]) + ",\n")
o.write("};\n")
